-- More sponsored placements (SHCWS-79), outage make-goods (SHCWS-179) and one reach view
-- per visitor and day (SHCWS-112).
--
-- 1. Placements `industry` (an industry page), `collection` (a collection page) and
--    `search` (/buscar, scoped by the category a query points at). They start closed and
--    without rates, like every placement: ops opens them once they have a price.
-- 2. Outage windows reported from outside Vercel (an uptime service's recovery webhook or
--    the GitHub Actions probe), and, per booking and day, what shwcs did about a day that
--    went four or more hours unserved: a make-good day after the booking, or a refund of
--    that day (the advertising terms, /terminos#publicidad).
--
-- Apply with `npm run db:migrate -- db/ad-placements-outages.sql`, after ad-self-serve.sql
-- and listing-notices.sql. Additive; idempotent.
BEGIN;

-- The placement list lives in two CHECKs written by db/ad-campaigns.sql. Their names were
-- generated by Postgres, so find them by what they say rather than by name.
DO $$
DECLARE c record;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint
    WHERE conrelid = 'ad_placements'::regclass AND contype = 'c'
      AND pg_get_constraintdef(oid) LIKE '%newsletter%'
  LOOP
    EXECUTE format('ALTER TABLE ad_placements DROP CONSTRAINT %I', c.conname);
  END LOOP;
  FOR c IN SELECT conname FROM pg_constraint
    WHERE conrelid = 'ad_campaigns'::regclass AND contype = 'c'
      AND pg_get_constraintdef(oid) LIKE '%placement%scope%'
  LOOP
    EXECUTE format('ALTER TABLE ad_campaigns DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;
ALTER TABLE ad_placements ADD CONSTRAINT ad_placements_id_check
  CHECK (id IN ('category','industry','collection','search','home','newsletter'));
-- A scoped placement always names its page (a category, industry or collection slug; for
-- search, the category the query points at); the others never do.
ALTER TABLE ad_campaigns ADD CONSTRAINT ad_campaigns_scope_check
  CHECK ((placement IN ('category','industry','collection','search')) = (scope <> ''));

-- Closed and without rates until ops opens them. One card on a search results page, so
-- the paid result never crowds out the organic ones; two on a page like a category.
INSERT INTO ad_placements (id, slots) VALUES ('industry', 2), ('collection', 2), ('search', 1)
ON CONFLICT (id) DO NOTHING;

-- The waitlist notice (db/ad-self-serve.sql) names every placement.
CREATE OR REPLACE FUNCTION notify_ad_waitlist() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE label text;
BEGIN
  IF NEW.enabled AND NOT OLD.enabled THEN
    label := CASE NEW.id WHEN 'category' THEN 'Página de categoría' WHEN 'home' THEN 'Inicio'
      WHEN 'industry' THEN 'Página de industria' WHEN 'collection' THEN 'Página de colección'
      WHEN 'search' THEN 'Resultados de búsqueda' ELSE 'Newsletter' END;
    PERFORM listing_notice(w.account_id,
      'ad:waitlist:' || NEW.id || ':' || w.account_id || ':' || extract(epoch FROM now())::bigint,
      'Ya puedes reservar el espacio patrocinado «' || label || '»',
      CASE WHEN w.solution_id IS NULL THEN '/account/solutions'
        ELSE '/account/solutions/' || w.solution_id || '/promote' END)
    FROM ad_waitlist w WHERE w.placement = NEW.id AND w.notified_at IS NULL;
    UPDATE ad_waitlist SET notified_at = now() WHERE placement = NEW.id AND notified_at IS NULL;
  END IF;
  RETURN NEW;
END $$;

-- A make-good day is its own booking: one free day right after the paid ones, in the same
-- placement and scope, paid (total 0) from the start. Keeping it apart leaves the paid
-- booking's days, and so every refund computed from them, exactly as sold.
ALTER TABLE ad_campaigns ADD COLUMN IF NOT EXISTS makegood_of uuid
  REFERENCES ad_campaigns(id) ON DELETE SET NULL;
ALTER TABLE ad_campaigns ADD COLUMN IF NOT EXISTS makegood_day date;
CREATE INDEX IF NOT EXISTS ad_campaigns_makegood ON ad_campaigns(makegood_of)
  WHERE makegood_of IS NOT NULL;

-- When the site could not serve, as an external monitor saw it. The same incident sent
-- twice (a retried webhook) is one row; a later report of it can only widen it.
CREATE TABLE IF NOT EXISTS site_outages (
 id uuid PRIMARY KEY,
 -- Who reported it: 'uptime' (an uptime service's webhook), 'github' (the probe in
 -- .github/workflows/uptime-probe.yml) or anything the reporter names, up to 40 chars.
 source varchar(40) NOT NULL,
 -- The reporter's own id for the incident, so a retry never adds a second window.
 external_id varchar(200) NOT NULL,
 started_at timestamptz NOT NULL,
 ended_at timestamptz NOT NULL,
 received_at timestamptz NOT NULL DEFAULT now(),
 -- Set once its days have been checked against bookings; cleared if a report widens it.
 processed_at timestamptz,
 -- A short lease so the webhook's own run and the daily cron never process it together.
 locked_until timestamptz,
 CHECK (ended_at > started_at),
 UNIQUE (source, external_id)
);
CREATE INDEX IF NOT EXISTS site_outages_window ON site_outages(started_at, ended_at);
CREATE INDEX IF NOT EXISTS site_outages_pending ON site_outages(received_at)
  WHERE processed_at IS NULL;

-- One decision per booking and day: never credited twice. `reason` says why it went the
-- way it did, for the founder's notice and for ops:
--   room       the day after the booking had room: a make-good day was added
--   noRoom     that day was full: the day is refunded
--   ended      the booking has no day left to extend into: refunded
--   stopped    the booking was cancelled or withdrawn: refunded
--   unlisted   the listing is no longer published, so a make-good could not run: refunded
CREATE TABLE IF NOT EXISTS ad_outage_credits (
 campaign_id uuid NOT NULL REFERENCES ad_campaigns(id) ON DELETE CASCADE,
 day date NOT NULL,
 -- Minutes of that day (Mexico City) covered by outage windows, all reporters merged.
 unserved_minutes integer NOT NULL CHECK (unserved_minutes BETWEEN 1 AND 1500),
 outcome text NOT NULL CHECK (outcome IN ('makegood','refund')),
 reason text NOT NULL CHECK (reason IN ('room','noRoom','ended','stopped','unlisted')),
 makegood_campaign_id uuid REFERENCES ad_campaigns(id) ON DELETE SET NULL,
 refund_amount integer NOT NULL DEFAULT 0 CHECK (refund_amount >= 0),
 -- refund_requested_amount of the booking after this refund was recorded: the refund's
 -- idempotency key is refund:<booking>:<this>, as for a cancellation or a withdrawal.
 refund_requested_total integer,
 -- none: nothing to refund (a free day) or a make-good. pending/failed: waiting for, or
 -- refused by, Stripe; the daily cron reissues it with the same key. issued: accepted.
 refund_status text NOT NULL DEFAULT 'none'
   CHECK (refund_status IN ('none','pending','issued','failed')),
 refund_error varchar(80),
 outage_ids uuid[] NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (campaign_id, day),
 CHECK ((outcome = 'makegood') = (reason = 'room'))
);
CREATE INDEX IF NOT EXISTS ad_outage_credits_refunds ON ad_outage_credits(updated_at)
  WHERE refund_status IN ('pending','failed');

-- SHCWS-112: one view per visitor, placement, scope and day for the reach estimate
-- (ad_placement_daily_views), like solution_view_visitors does for listing views (§55).
-- visitor_hash is HMAC-SHA256(VIEW_HASH_SECRET, ip + day): never the IP, and a new hash
-- every day. Rows only live long enough to dedupe today; the monitor cron deletes those
-- older than three days. Without VIEW_HASH_SECRET nothing is written here and views are
-- counted as before.
CREATE TABLE IF NOT EXISTS ad_placement_view_visitors (
 placement text NOT NULL REFERENCES ad_placements(id),
 scope varchar(40) NOT NULL DEFAULT '',
 day date NOT NULL,
 visitor_hash text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (placement, scope, day, visitor_hash)
);
CREATE INDEX IF NOT EXISTS ad_placement_view_visitors_day ON ad_placement_view_visitors(day);

COMMIT;
