-- SHCWS-58/60: «Publica tu necesidad». A buyer describes a need (brief); founders whose
-- published listings fit it are told and may send one proposal each; the buyer compares
-- the proposals and picks whom to talk to, which opens an ordinary contact request.
-- Ops reads the brief (the buyer sent it to be attended, consent brief-v1) and may hide it
-- or send the buyer a short list of listings. Contract: docs/briefs.md.
-- Additive and re-runnable; after contact-requests.sql, search-alerts.sql and
-- ops-console.sql.

-- A new notice category for briefs, proposals and short lists, with its own email
-- preference (on unless turned off: the buyer asked, the founder's listing fits).
ALTER TABLE account_notifications DROP CONSTRAINT IF EXISTS account_notifications_category_check;
ALTER TABLE account_notifications ADD CONSTRAINT account_notifications_category_check
  CHECK (category IN ('contact', 'solution', 'security', 'account', 'community', 'alert', 'brief'));
ALTER TABLE notification_preferences
  ADD COLUMN IF NOT EXISTS brief_email boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS buyer_briefs (
  -- Generated by the browser, so retrying the same submit never creates a second brief.
  id uuid PRIMARY KEY,
  buyer_id uuid NOT NULL REFERENCES auth_accounts(id) ON DELETE CASCADE,
  problem text NOT NULL CHECK (char_length(problem) BETWEEN 20 AND 2000),
  budget text NOT NULL DEFAULT '' CHECK (char_length(budget) <= 200),
  -- Same stored values as contact_requests.details.timeline, so choosing a proposal can
  -- prefill the contact form.
  timeline text NOT NULL
    CHECK (timeline IN ('Estoy explorando', 'Este mes', 'En 1–3 meses', 'Más adelante')),
  company_size text NOT NULL CHECK (company_size IN ('micro', 'pyme', 'mediana', 'corporativo')),
  industry text CHECK (industry IS NULL OR char_length(industry) BETWEEN 1 AND 60),
  country text CHECK (country IS NULL OR country ~ '^[A-Z]{2}$'),
  categories text[] NOT NULL CHECK (cardinality(categories) BETWEEN 1 AND 3),
  capabilities text[] NOT NULL DEFAULT '{}' CHECK (cardinality(capabilities) <= 8),
  consent_version text NOT NULL CHECK (char_length(consent_version) BETWEEN 1 AND 40),
  consent_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Thirty days to receive proposals; the buyer keeps reading what arrived.
  expires_at timestamptz NOT NULL DEFAULT now() + interval '30 days',
  closed_at timestamptz,
  hidden_at timestamptz,
  hidden_reason text CHECK (hidden_reason IS NULL OR char_length(hidden_reason) <= 1000),
  hidden_by uuid REFERENCES auth_accounts(id) ON DELETE SET NULL,
  CHECK ((hidden_at IS NULL) = (hidden_reason IS NULL))
);
CREATE INDEX IF NOT EXISTS buyer_briefs_buyer ON buyer_briefs (buyer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS buyer_briefs_open ON buyer_briefs (created_at DESC)
  WHERE hidden_at IS NULL AND closed_at IS NULL;

-- Which published listings fit a brief, decided by the app (src/lib/briefs) when the brief
-- is created and again when a listing is published. One row per listing; founder_id is the
-- listing's owner when it matched, and every read also checks the current owner.
CREATE TABLE IF NOT EXISTS buyer_brief_matches (
  brief_id uuid NOT NULL REFERENCES buyer_briefs(id) ON DELETE CASCADE,
  solution_id uuid NOT NULL REFERENCES founder_solutions(id) ON DELETE CASCADE,
  founder_id uuid NOT NULL REFERENCES auth_accounts(id) ON DELETE CASCADE,
  matched_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (brief_id, solution_id),
  UNIQUE (brief_id, solution_id, founder_id)
);
CREATE INDEX IF NOT EXISTS buyer_brief_matches_founder
  ON buyer_brief_matches (founder_id, matched_at DESC);

-- One proposal per founder and brief, only for a listing that matched it (the composite
-- foreign key), so nobody proposes to a brief they were never shown.
CREATE TABLE IF NOT EXISTS buyer_brief_proposals (
  id uuid PRIMARY KEY,
  brief_id uuid NOT NULL,
  solution_id uuid NOT NULL,
  founder_id uuid NOT NULL,
  message text NOT NULL CHECK (char_length(message) BETWEEN 20 AND 2000),
  price text NOT NULL CHECK (char_length(price) BETWEEN 1 AND 200),
  timeline text NOT NULL CHECK (char_length(timeline) BETWEEN 1 AND 200),
  created_at timestamptz NOT NULL DEFAULT now(),
  -- The buyer chose to talk to this founder: the contact request that opened.
  chosen_at timestamptz,
  contact_request_id uuid REFERENCES contact_requests(id) ON DELETE SET NULL,
  FOREIGN KEY (brief_id, solution_id, founder_id)
    REFERENCES buyer_brief_matches (brief_id, solution_id, founder_id) ON DELETE CASCADE,
  UNIQUE (brief_id, founder_id)
);
CREATE INDEX IF NOT EXISTS buyer_brief_proposals_brief
  ON buyer_brief_proposals (brief_id, created_at);
CREATE INDEX IF NOT EXISTS buyer_brief_proposals_founder
  ON buyer_brief_proposals (founder_id, created_at DESC);

-- A short list ops writes for the buyer: up to three published listings and a note. One per
-- brief; the id comes from ops' browser so a retried send is the same short list.
CREATE TABLE IF NOT EXISTS buyer_brief_shortlists (
  id uuid PRIMARY KEY,
  brief_id uuid NOT NULL UNIQUE REFERENCES buyer_briefs(id) ON DELETE CASCADE,
  solution_ids uuid[] NOT NULL CHECK (cardinality(solution_ids) BETWEEN 1 AND 3),
  note text NOT NULL CHECK (char_length(note) BETWEEN 10 AND 2000),
  created_by uuid REFERENCES auth_accounts(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
