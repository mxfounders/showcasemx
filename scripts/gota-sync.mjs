// Draws Gota, Flouvia's icon set, into shwcs and shwcs-ops from Gota's repository (its dist/,
// already built there). Gota is not on npm until its v1, so the build cannot install it.
//
//   npm run gota:sync                      after importing an icon, or giving one a new style
//   npm run gota:sync -- --from <path>     Gota's repository (default ../gota or ../flouvia-icons)
//
// For each app (src/ and ops/src/) it reads which icons the code imports from
// '@/components/icons/gota' and which Gota props each one gets (variant, weight, enclosure,
// slash), draws them with Gota's engine and writes:
//   components/icons/gota/<icon>.ts   one component per icon with its drawings, typed with the
//                                     props it was drawn for; Gota's LICENSE beside them (MIT)
//   components/icons/gota/index.ts    the list the code imports from
//   components/icons/gota/package.json  marks them free of side effects, so a page's bundle
//                                     carries only the icons it uses, not the whole list
// The component itself is src/components/icons/gota-base.tsx (ops/ gets a copy: the two apps
// build separately). Every generated file says so in its first line. At Gota's v1,
// @flouvia/gota replaces all of it.
import { existsSync, readdirSync, statSync } from 'node:fs';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APPS = [
  { name: 'shwcs', src: join(root, 'src') },
  { name: 'shwcs-ops', src: join(root, 'ops', 'src'), copyBase: true },
];
const BASE = join(root, 'src', 'components', 'icons', 'gota-base.tsx');
// Where a drawing's masks take each instance's id: GOTA_ID in gota-base.tsx
const GOTA_ID = '__gota__';

// ── Gota's repository ───────────────────────────────────────────────────
const fromAt = process.argv.indexOf('--from');
const candidates =
  fromAt > -1
    ? [resolve(process.argv[fromAt + 1])]
    : ['../gota', '../flouvia-icons'].map(p => resolve(root, p));
const repo = candidates.find(p => existsSync(join(p, 'dist', 'index.js')));
if (!repo) {
  console.error(
    `Gota's dist/ is not in ${candidates.join(' or ')}: build it there (node scripts/build.mjs) or pass --from <path>.`,
  );
  process.exit(1);
}
const gota = await import(pathToFileURL(join(repo, 'dist', 'index.js')).href);
const { version } = JSON.parse(await readFile(join(repo, 'package.json'), 'utf8'));
const NOTE = `Generated by scripts/gota-sync.mjs from Gota ${version}: do not edit. @flouvia/gota replaces it at v1.`;

const pascal = kebab =>
  kebab
    .split('-')
    .map(w => w[0].toUpperCase() + w.slice(1))
    .join('');
/** Gota's export for an icon (bell-off → BellOffIcon), as its own build names it. */
const exportName = name => `${pascal(name)}Icon`;
const byExport = new Map(Object.keys(gota.icons).map(name => [exportName(name), name]));

// ── What each app imports, and with which props ─────────────────────────
const IMPORT =
  /import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*['"](?:@\/components\/icons\/gota|\.\/gota)['"]/g;
const NOT_ICONS = new Set(['GotaIcon', 'GotaIconProps']);
const ALL = {
  variant: ['outline', 'fill'],
  weight: ['regular', 'light', 'bold'],
  enclosure: [null, 'circle', 'square'],
  slash: [false, true],
};

function* sources(dir) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      if (path !== join(dir, 'components', 'icons', 'gota')) yield* sources(path);
    } else if (/\.tsx?$/.test(entry)) yield path;
  }
}

/** Where an opening tag that starts at i ends, past braces and quoted values. */
function tagEnd(code, i) {
  let depth = 0;
  let quote = null;
  for (let k = i + 1; k < code.length; k++) {
    const c = code[k];
    if (quote) {
      if (c === quote && code[k - 1] !== '\\') quote = null;
    } else if (c === '"' || c === "'" || c === '`') quote = c;
    else if (c === '{') depth++;
    else if (c === '}') depth--;
    else if (c === '>' && depth === 0) return k;
  }
  return code.length;
}

/** The values a prop takes in a tag: the literal written, every value for an expression. */
function valuesOf(tag, prop) {
  if (prop === 'slash') {
    const m = tag.match(/\sslash(?:=\{([^}]*)\})?(?=[\s/>=])/);
    if (!m) return [];
    const v = m[1]?.trim();
    return v === undefined || v === 'true' ? [true] : v === 'false' ? [] : ALL.slash;
  }
  const m = tag.match(new RegExp(`\\s${prop}=(?:"([^"]*)"|'([^']*)'|\\{([^}]*)\\})`));
  if (!m) return [];
  const literal = m[1] ?? m[2] ?? m[3].trim().match(/^(['"])(.*)\1$/)?.[2];
  if (literal !== undefined) return [literal];
  if (prop === 'weight' && /^\d*\.?\d+$/.test(m[3].trim())) return [Number(m[3])];
  return ALL[prop];
}

async function usage(src) {
  const icons = new Map(); // Gota name → { variant, weight, enclosure, slash } sets
  for (const file of sources(src)) {
    const code = await readFile(file, 'utf8');
    const locals = new Map(); // local name → Gota name
    for (const [, list] of code.matchAll(IMPORT))
      for (const spec of list.split(',')) {
        const [imported, local = imported] = spec
          .trim()
          .replace(/^type\s+/, '')
          .split(/\s+as\s+/);
        if (!imported || NOT_ICONS.has(imported)) continue;
        if (!byExport.has(imported))
          throw new Error(`${relative(root, file)}: Gota has no ${imported}.`);
        const name = byExport.get(imported);
        locals.set(local, name);
        if (!icons.has(name))
          icons.set(name, {
            variant: new Set(['outline']),
            weight: new Set(['regular']),
            enclosure: new Set([null]),
            slash: new Set([false]),
          });
      }
    for (const [local, name] of locals)
      for (const m of code.matchAll(new RegExp(`<${local}(?=[\\s/>])`, 'g'))) {
        const tag = code.slice(m.index, tagEnd(code, m.index));
        for (const prop of Object.keys(ALL))
          for (const value of valuesOf(tag, prop)) icons.get(name)[prop].add(value);
      }
  }
  return icons;
}

// ── Drawing ─────────────────────────────────────────────────────────────
/** A drawing's key; gotaKey in gota-base.tsx computes the same one from the props. */
const keyOf = ({ variant, weight, enclosure, slash }) =>
  [variant, weight !== 'regular' && weight, enclosure, slash && 'slash'].filter(Boolean).join('/');

function draw(name, { variant, weight, enclosure, slash }) {
  const picked = gota.pick(gota.iconData(name), { enclosure, slash });
  return gota.render(picked.icon, {
    style: variant,
    weight: gota.WEIGHTS[weight] ?? weight,
    enclosure: picked.enclosure,
    slash: picked.slash,
    id: GOTA_ID,
  });
}

const literal = v => (typeof v === 'string' ? `'${v}'` : String(v));
/** The props an icon was drawn for, as the type of its component. */
function propsType(sets) {
  const fields = [];
  if (sets.variant.size > 1) fields.push(`variant?: ${[...sets.variant].map(literal).join(' | ')}`);
  if (sets.weight.size > 1) fields.push(`weight?: ${[...sets.weight].map(literal).join(' | ')}`);
  if (sets.enclosure.size > 1)
    fields.push(`enclosure?: ${[...sets.enclosure].map(literal).join(' | ')}`);
  if (sets.slash.size > 1) fields.push('slash?: boolean');
  return fields.length ? `GotaIconProps<{ ${fields.join('; ')} }>` : 'GotaIconProps';
}

async function sync({ name: app, src, copyBase }) {
  const icons = await usage(src);
  const dir = join(src, 'components', 'icons');
  const out = join(dir, 'gota');
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  await copyFile(join(repo, 'LICENSE'), join(out, 'LICENSE'));
  await writeFile(
    join(out, 'package.json'),
    `${JSON.stringify({ '//': NOTE, private: true, sideEffects: false }, null, 2)}\n`,
  );

  let drawings = 0;
  const names = [...icons.keys()].sort();
  for (const name of names) {
    const sets = icons.get(name);
    const entries = [];
    for (const variant of sets.variant)
      for (const weight of sets.weight)
        for (const enclosure of sets.enclosure)
          for (const slash of sets.slash) {
            const props = { variant, weight, enclosure, slash };
            entries.push(
              `  ${JSON.stringify(keyOf(props))}: ${JSON.stringify(draw(name, props))},`,
            );
          }
    drawings += entries.length;
    await writeFile(
      join(out, `${name}.ts`),
      [
        `// ${NOTE}`,
        "// Gota's drawings © Flouvia, S.A.S. de C.V., MIT (./LICENSE).",
        "import { createElement } from 'react';",
        "import { GotaSvg, type GotaIconProps } from '../gota-base';",
        '',
        'const drawings = {',
        ...entries,
        '};',
        '',
        `export function ${exportName(name)}(props: ${propsType(sets)}) {`,
        '  return createElement(GotaSvg, { ...props, drawings });',
        '}',
        '',
      ].join('\n'),
    );
  }
  await writeFile(
    join(out, 'index.ts'),
    [
      `// ${NOTE}`,
      '// Every Gota icon this app imports. For a new one (or a new variant, weight, enclosure or',
      '// slash on one), import it from here and run `npm run gota:sync`. See ../gota-base.tsx.',
      "export type { GotaIcon, GotaIconProps } from '../gota-base';",
      ...names.map(name => `export { ${exportName(name)} } from './${name}';`),
      '',
    ].join('\n'),
  );
  if (copyBase) {
    const note = `// Copy of src/components/icons/gota-base.tsx by scripts/gota-sync.mjs: edit it there.\n`;
    await writeFile(join(dir, 'gota-base.tsx'), note + (await readFile(BASE, 'utf8')));
  }
  console.log(
    `${app}: ${names.length} icons, ${drawings} drawings, from Gota ${version} → ${relative(root, out)}`,
  );
}

for (const app of APPS) await sync(app);
